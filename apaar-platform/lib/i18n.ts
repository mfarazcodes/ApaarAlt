export const DICTIONARIES: Record<Lang, Record<Key, string>> = { en: EN, hi: HI };

/** Looks a string up and fills {placeholders}. Falls back to English, then to the key, so a gap is never blank. */
export function translate(lang: Lang, key: Key | string, vars?: Record<string, string | number>): string {
  const table = DICTIONARIES[lang] as Record<string, string>;
  const text = table[key] ?? (EN as Record<string, string>)[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (_m, name: string) => String(vars[name] ?? `{${name}}`)) : text;
}

/** One name per portal on every surface. The /admin page is "Colleges" for a registrar and "AICTE" for an AICTE officer. */
export function portalKey(href: string, role?: string): Key {
  if (href === "/student") return "portal.students";
  if (href === "/employer") return "portal.employers";
  return role === "AICTE" ? "portal.aicte" : "portal.colleges";
}
